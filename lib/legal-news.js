/**
 * Get news filtered and sorted
 */
export function getLegalNews({ category = 'all', limit = 50, priority = null } = {}) {
  let news = [...LEGAL_NEWS];

  if (category !== 'all') {
    news = news.filter(n => n.category === category);
  }
  if (priority) {
    news = news.filter(n => n.priority === priority);
  }

  // Sort by date desc
  news.sort((a, b) => new Date(b.date) - new Date(a.date));

  return news.slice(0, limit);
}

export function getNewsById(id) {
  return LEGAL_NEWS.find(n => n.id === id) || null;
}
